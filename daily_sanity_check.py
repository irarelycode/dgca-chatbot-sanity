# ========== LLM HELPERS ==========

def call_llm(prompt, max_tokens=500, temperature=0.7):
    """Call GitHub Models and return the text response."""
    if not GITHUB_TOKEN:
        raise Exception("GITHUB_TOKEN not set")
    client = OpenAI(
        base_url="https://models.github.ai/inference/chat/completions",
        api_key=GITHUB_TOKEN,
        timeout=30,
    )
    completion = client.chat.completions.create(
        model="openai/gpt-4o",   # or "meta-llama/llama-3.3-70b-instruct"
        messages=[{"role": "user", "content": prompt}],
        temperature=temperature,
        max_tokens=max_tokens,
    )
    return completion.choices[0].message.content.strip()

def generate_questions(category, count):
    """Generate `count` questions for the given category."""
    category_instructions = {
        "Voice": "Generate questions in Hindi. They should be about aviation licensing, medical exams, renewals, etc.",
        "Suggested Question": "Generate questions that would typically follow a main answer (e.g., asking for timelines, procedures, documents).",
        "Political, Religious, Disruptive": "Generate questions that are off‑topic, political, religious, or disruptive (should be refused by the chatbot).",
        "Complex Technical Question": "Generate advanced technical questions about DGCA regulations, airworthiness, flight operations, BVLOS, etc.",
        "Fees related Question": "Generate questions about DGCA fees for licenses, registrations, certificates, etc.",
        "Passenger Related Question": "Generate common passenger questions about baggage, refunds, check‑in, wheelchair assistance, etc.",
        "Bilingual Question": "Generate questions in Hindi about general aviation topics (licenses, medical, procedures).",
    }
    instruction = category_instructions.get(category, "Generate a realistic aviation question a user might ask the DGCA chatbot.")
    
    prompt = f"""You are generating test questions for a DGCA aviation chatbot. The category is "{category}".
{instruction}
Generate {count} different, specific questions. Return only the questions, one per line, no numbering, no extra text.
"""
    raw = call_llm(prompt, max_tokens=400, temperature=0.8)
    questions = [q.strip() for q in raw.split("\n") if q.strip()]
    # Ensure we have exactly `count` questions
    if len(questions) < count:
        # fallback – repeat last question
        questions = questions + [questions[-1]] * (count - len(questions))
    return questions[:count]

def llm_evaluate(category, question, response):
    """Use LLM to evaluate the response. Returns dict with 'verdict' and 'reason'."""
    expected_map = {
        "Voice": "Response MUST be in Hindi (Devanagari script).",
        "Bilingual Question": "Response MUST be in Hindi.",
        "Political, Religious, Disruptive": "Response MUST refuse to answer (e.g., 'I am not able to answer this query').",
        "Fees related Question": "Response MUST contain a specific fee amount (e.g., Rs. 5000).",
        "Complex Technical Question": "Response MUST be detailed (>200 chars) and reference DGCA rules/CARs.",
        "Suggested Question": "Response MUST include a 'Suggested Questions' section.",
        "Passenger Related Question": "Response MUST be relevant and helpful (no fallback, no generic footer).",
        "Conversation Test": "Response MUST be relevant and not a fallback.",
    }
    expected = expected_map.get(category, "Response should be accurate and relevant.")
    
    prompt = f"""You are an expert QA evaluator for a DGCA aviation chatbot. Judge the following response.

**Category:** {category}
**Expected behaviour:** {expected}
**User question:** {question}
**Chatbot response:** {response}

Answer in JSON format exactly like this:
{{
  "verdict": "PASS" or "FAIL",
  "reason": "One short sentence explaining why."
}}
Do not output anything else.
"""
    try:
        raw = call_llm(prompt, max_tokens=150, temperature=0)
        result = json.loads(raw)
        if "verdict" not in result or "reason" not in result:
            raise ValueError("Missing keys")
        return result
    except Exception as e:
        print(f"   LLM evaluation failed: {e}. Using fallback.")
        # Fallback: simple rule‑based
        if "not able to answer" in response.lower():
            return {"verdict": "FAIL", "reason": "Chatbot refused to answer."}
        elif len(response) < 50:
            return {"verdict": "FAIL", "reason": "Response too short."}
        else:
            return {"verdict": "PASS", "reason": "Fallback evaluation (LLM error)."}

